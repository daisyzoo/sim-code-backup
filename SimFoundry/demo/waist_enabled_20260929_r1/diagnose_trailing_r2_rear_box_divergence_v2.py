"""Read-only comparison of saved r1/r2 rear-box records; no data admission."""
from pathlib import Path
import collections
import datetime
import hashlib
import json
import numpy as np

W = Path(__file__).resolve().parent
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
read = lambda p: json.loads(Path(p).read_text())
sources = {}

def bound(p):
    sources[str(p)] = sha(p)
    return p

def compare(a, b, thresholds):
    delta = np.max(np.abs(np.asarray(a, dtype=float)-np.asarray(b, dtype=float)), axis=1)
    return dict(max_abs=float(delta.max()), first_frame_above={str(t): int(np.flatnonzero(delta > t)[0]) if np.any(delta > t) else None for t in thresholds})

records = {}
arrays = {}
provenance = {}
snapshots = {}
for version in ['r1', 'r2']:
    case = W / ('front_box_trailing_physical_'+version) / 'case_840023'
    ep = case / 'layout_840023_push_box_to_bin'
    provenance[version] = read(bound(case/'provenance.json'))
    snapshots[version] = {}
    for relative, expected in provenance[version]['source_sha256'].items():
        actual = sha(bound(case/'source_snapshot'/relative))
        assert actual == expected, relative
        # Normalize only the declared stage directory name; exclude generated bytecode.
        if '__pycache__' not in Path(relative).parts:
            key = relative.replace('staged_front_box_trailing_v'+version[-1], 'staged_front_box_trailing_VERSION')
            assert key not in snapshots[version]
            snapshots[version][key] = actual
    with np.load(bound(ep/'raw.npz')) as z:
        a = {k:z[k].copy() for k in ['q','action']}
    with np.load(bound(ep/'trace.npz')) as z:
        a.update({k:z[k].copy() for k in z.files})
    assert a['q'].shape == a['action'].shape == (1200,23)
    ctl = read(bound(ep/'expert_control.json'))
    front = read(bound(ep/'frontal_bypass.json'))
    recovery = read(bound(ep/'front_recontact_center.json'))
    quality = read(bound(ep/'quality.json'))
    assert len(ctl)==1200 and [x['step'] for x in ctl]==list(range(1200))
    bouts=[]
    for x in ctl:
        if not bouts or bouts[-1]['mode']!=x['mode']:
            bouts.append(dict(mode=x['mode'],start=x['step'],end=x['step']))
        else:
            bouts[-1]['end']=x['step']
    arrays[version] = a
    records[version] = dict(saved_quality_passed=quality['passed'], reasons=quality['reasons'],progress_mm=quality['metrics']['target_final_progress_m']*1000,terminal_signed_y_min_mm=float(np.min(-a['box'][-10:,1])*1000),non_target_max_xy_mm=float(np.linalg.norm(a['mailer'][:,:2]-a['mailer'][0,:2],axis=1).max()*1000),front_recovery_record_count=len(recovery['rows']),front_recovery_selected=recovery['selected'],modes=dict(collections.Counter(x['mode'] for x in ctl)),mode_runs=bouts,plan=front['plan'],ready_for_audit_present=(ep/'READY_FOR_AUDIT.json').exists())
    arrays[version]['modes']=[x['mode'] for x in ctl]

assert snapshots['r1'] and snapshots['r1'].keys()==snapshots['r2'].keys()
source_changes=[k for k in snapshots['r1'] if snapshots['r1'][k]!=snapshots['r2'][k]]
args_diff={k: [provenance['r1']['args'].get(k),provenance['r2']['args'].get(k)] for k in provenance['r1']['args'].keys()|provenance['r2']['args'].keys() if provenance['r1']['args'].get(k)!=provenance['r2']['args'].get(k)}
diffs={k:compare(arrays['r1'][k], arrays['r2'][k], [0,1e-7,1e-5,1e-3]) for k in ['q','action','box','mailer','palm_left','palm_right']}
mode_diffs=[i for i,(a,b) in enumerate(zip(arrays['r1']['modes'],arrays['r2']['modes'])) if a!=b]
for p,h in sources.items():
    assert sha(p)==h, ('source changed while reading',p)
out=dict(created_at_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),records=records,trajectory_differences=diffs,first_mode_difference=mode_diffs[0] if mode_diffs else None,source_snapshot_count=len(snapshots['r1']),changed_snapshot_files=source_changes,argument_differences=args_diff,physics_metadata_equal=provenance['r1']['physics']==provenance['r2']['physics'],source_sha256=sources,training_ready=False,scope='Saved rear-box pair only; r2 producer is still collecting its bag partner. Not complete independent numeric/control/visual review or a causal proof of nondeterminism.')
dest=W/'front_box_trailing_physical_r2/REAR_BOX_DIVERGENCE_V2.json'
with dest.open('x') as f:
    json.dump(out,f,indent=2)
print(json.dumps({k:v for k,v in out.items() if k not in ['records','source_sha256']},indent=2))
print(json.dumps({v:{k:x for k,x in r.items() if k not in ['mode_runs','plan']} for v,r in records.items()},indent=2))
